// 随机取 n 个（洗牌法）
export const pickRandom = (n = 6, exclude = []) => {
  const pool = QUESTIONS.filter((q) => !exclude.includes(q))
  const a = (pool.length >= n ? pool : QUESTIONS).slice()
  for (let i = a.length - 1; i > 0; i--) {
    const j = Math.floor(Math.random() * (i + 1))
    ;[a[i], a[j]] = [a[j], a[i]]
  }
  return a.slice(0, n)
}
